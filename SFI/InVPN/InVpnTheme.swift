import SwiftUI

/// INVPN palette — mirrors the Android Greek theme (Aegean / Bronze / Marble).
enum InVpnTheme {
    static let sea = Color(red: 0x1C / 255, green: 0x5D / 255, blue: 0x7C / 255)   // #1C5D7C
    static let bronze = Color(red: 0xC9 / 255, green: 0xA2 / 255, blue: 0x4B / 255) // #C9A24B
    static let marble = Color(red: 0xF3 / 255, green: 0xEF / 255, blue: 0xE6 / 255) // #F3EFE6
    static let ink = Color(red: 0x0D / 255, green: 0x2A / 255, blue: 0x3A / 255)    // #0D2A3A
}
